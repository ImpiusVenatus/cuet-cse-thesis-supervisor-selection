ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "students_import_2004.csv"

pattern = re.compile(r"^\s*(.+?)\s+(20\d{5})\s*$")

def main() -> None:
    rows_out: list[dict[str, str | int]] = []
    merit = 1
    for raw_line in RAW.strip().splitlines():
        line = raw_line.strip()
        if not line:
            continue
        m = pattern.match(line)
        if not m:
            raise SystemExit(f"Could not parse line: {line!r}")
        name, sid = m.group(1).strip(), m.group(2)
        email = f"u{sid}@student.cuet.ac.bd"
        rows_out.append(
            {
                "student_id": sid,
                "name": name,
                "merit_rank": merit,
                "email": email,
            }
        )
        merit += 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["student_id", "name", "merit_rank", "email"])
        w.writeheader()
        for r in rows_out:
            w.writerow(
                {
                    "student_id": r["student_id"],
                    "name": r["name"],
                    "merit_rank": r["merit_rank"],
                    "email": r["email"],
                }
            )

    print(f"Wrote {len(rows_out)} rows to {OUT}")


if __name__ == "__main__":
    main()
